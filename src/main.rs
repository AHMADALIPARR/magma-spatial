use std::{env, fs, process};

// MAGMA MVP: compile statically-addressed Brainfuck into a combinational
// Verilog datapath. There is no program counter in the synthesized design.
// Logical cells are 16-bit wrapping integers; source code uses BF syntax.
fn main() {
    let args: Vec<String> = env::args().collect();
    if args.len() != 4 || args[1] != "compile" {
        eprintln!("usage: magma-spatial compile <source.bf> <output.v>");
        process::exit(2);
    }
    let source = fs::read_to_string(&args[2]).unwrap_or_else(|e| {
        eprintln!("cannot read source: {e}"); process::exit(1)
    });
    let mut pointer: i64 = 0;
    let mut min_pointer: i64 = 0;
    let mut max_pointer: i64 = 0;
    let mut ops: Vec<(char, i64)> = Vec::new();
    for (index, c) in source.chars().enumerate() {
        match c {
            '>' => pointer += 1,
            '<' => pointer -= 1,
            '+' | '-' | '.' => ops.push((c, pointer)),
            '[' | ']' => {
                eprintln!("dynamic loop at character {index}: feedback synthesis not implemented");
                process::exit(1);
            }
            ',' => {
                eprintln!("input at character {index}: streaming input synthesis not implemented");
                process::exit(1);
            }
            _ => {}
        }
        min_pointer = min_pointer.min(pointer);
        max_pointer = max_pointer.max(pointer);
    }
    // Independent memory cells are separate combinational datapaths.
    let count = (max_pointer - min_pointer + 1) as usize;
    if count > 4096 {
        eprintln!("more than 4096 addressed cells: resource guard");
        process::exit(1);
    }
    let mut deltas: Vec<i64> = vec![0; count];
    let mut outputs: Vec<(usize, i64)> = Vec::new();
    for (op, position) in &ops {
        let index = (position - min_pointer) as usize;
        match op {
            '+' => deltas[index] += 1,
            '-' => deltas[index] -= 1,
            '.' => outputs.push((index, deltas[index])),
            _ => unreachable!(),
        }
    }
    let mut v = String::from("// Generated by MAGMA spatial compiler v0.1\n");
    v.push_str("// Each addressed tape cell is an independent combinational lane.\n");
    v.push_str("module magma_spatial (\n");
    let mut ports: Vec<String> = Vec::new();
    for i in 0..count {
        ports.push(format!("    input wire [15:0] cell_in_{i}"));
        ports.push(format!("    output wire [15:0] cell_out_{i}"));
    }
    for i in 0..outputs.len() {
        ports.push(format!("    output wire [15:0] print_{i}"));
    }
    v.push_str(&ports.join(",\n"));
    v.push_str("\n);\n");
    for (i, delta) in deltas.iter().enumerate() {
        // Cast via modular reduction to define 16-bit wraparound.
        let constant = delta.rem_euclid(65536);
        v.push_str(&format!("  assign cell_out_{i} = cell_in_{i} + 16'd{constant};\n"));
    }
    for (i, (cell, delta)) in outputs.iter().enumerate() {
        let constant = delta.rem_euclid(65536);
        v.push_str(&format!("  assign print_{i} = cell_in_{cell} + 16'd{constant};\n"));
    }
    v.push_str("endmodule\n");
    fs::write(&args[3], v).unwrap_or_else(|e| {
        eprintln!("cannot write netlist: {e}"); process::exit(1)
    });
    println!("compiled: {} cells, {} writes, {} output taps, no instruction pointer", count, ops.iter().filter(|(c,_)| *c == '+' || *c == '-').count(), outputs.len());
}
