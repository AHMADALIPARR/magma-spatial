use crate::lower::Lowered;

/// Reduce a delta to its 16-bit wrapping constant, as emitted.
fn constant(delta: i64) -> i64 {
    delta.rem_euclid(65536)
}

/// Emit the Verilog datapath for a lowered program. Each addressed
/// cell is an independent combinational lane: a 16-bit input, a
/// 16-bit output offset by the cell's net delta, plus one
/// `print_N` output tap per print operation. There is no program
/// counter in the generated design.
pub fn emit(lowered: &Lowered) -> String {
    let count = lowered.deltas.len();
    let mut v = String::from("// Generated by MAGMA spatial compiler v0.1\n");
    v.push_str("// Each addressed tape cell is an independent combinational lane.\n");
    v.push_str("module magma_spatial (\n");
    let mut ports: Vec<String> = Vec::new();
    for i in 0..count {
        ports.push(format!("    input wire [15:0] cell_in_{i}"));
        ports.push(format!("    output wire [15:0] cell_out_{i}"));
    }
    for i in 0..lowered.output_taps.len() {
        ports.push(format!("    output wire [15:0] print_{i}"));
    }
    v.push_str(&ports.join(",\n"));
    v.push_str("\n);\n");
    for (i, delta) in lowered.deltas.iter().enumerate() {
        // Cast via modular reduction to define 16-bit wraparound.
        let constant = constant(*delta);
        v.push_str(&format!(
            "  assign cell_out_{i} = cell_in_{i} + 16'd{constant};\n"
        ));
    }
    for (i, (cell, delta)) in lowered.output_taps.iter().enumerate() {
        let constant = constant(*delta);
        v.push_str(&format!(
            "  assign print_{i} = cell_in_{cell} + 16'd{constant};\n"
        ));
    }
    v.push_str("endmodule\n");
    v
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::lower::lower;
    use crate::parse::parse;

    fn netlist(source: &str) -> String {
        emit(&lower(&parse(source).unwrap()).unwrap())
    }

    #[test]
    fn parallel_example_layout() {
        let v = netlist("+++>+++++>--.<.<.");
        assert!(v.contains("module magma_spatial ("));
        assert!(v.contains("assign cell_out_0 = cell_in_0 + 16'd3;"));
        assert!(v.contains("assign cell_out_1 = cell_in_1 + 16'd5;"));
        assert!(v.contains("assign cell_out_2 = cell_in_2 + 16'd65534;"));
        assert!(v.contains("assign print_0 = cell_in_2 + 16'd65534;"));
        assert!(v.contains("assign print_1 = cell_in_1 + 16'd5;"));
        assert!(v.contains("assign print_2 = cell_in_0 + 16'd3;"));
        assert!(v.trim_end().ends_with("endmodule"));
    }

    #[test]
    fn deltas_wrap_modulo_2_to_the_16() {
        // 65537 decrements wrap to the constant 65535.
        let v = netlist(&"-".repeat(65537));
        assert!(v.contains("assign cell_out_0 = cell_in_0 + 16'd65535;"));
        // A full turn of increments wraps to zero.
        let v = netlist(&"+".repeat(65536));
        assert!(v.contains("assign cell_out_0 = cell_in_0 + 16'd0;"));
    }

    #[test]
    fn no_prints_no_taps() {
        let v = netlist("+++");
        assert!(!v.contains("print_"));
        assert_eq!(v.matches("assign").count(), 1);
    }
}
